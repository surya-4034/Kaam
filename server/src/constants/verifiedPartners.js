/**
 * Self-healing schema validation and seed executor
 */
export async function ensureVerifiedPartnersSeeded(db) {
  if (!db) return;

  // 1. Ensure columns exist on worker_profiles
  await new Promise((resolve) => {
    db.all("PRAGMA table_info(worker_profiles)", (err, columns) => {
      if (err || !Array.isArray(columns)) return resolve();
      const colNames = columns.map(c => c.name);

      const toAdd = [
        { name: 'packages_json', type: 'TEXT' },
        { name: 'categories_json', type: 'TEXT' },
        { name: 'latitude', type: 'REAL' },
        { name: 'longitude', type: 'REAL' },
        { name: 'visiting_charge', type: 'REAL DEFAULT 149' },
        { name: 'experience_years', type: 'INTEGER DEFAULT 1' },
        { name: 'is_account_locked', type: 'INTEGER DEFAULT 0' },
        { name: 'kyc_status', type: "TEXT DEFAULT 'VERIFIED'" },
        { name: 'rating_average', type: 'REAL DEFAULT 5.0' },
        { name: 'completed_jobs_count', type: 'INTEGER DEFAULT 0' }
      ];

      const missing = toAdd.filter(col => !colNames.includes(col.name));
      if (missing.length === 0) return resolve();

      let completed = 0;
      missing.forEach(col => {
        db.run(`ALTER TABLE worker_profiles ADD COLUMN ${col.name} ${col.type}`, () => {
          completed++;
          if (completed >= missing.length) resolve();
        });
      });
    });
  });

  // 2. Insert or Replace all 4 verified partners into users and worker_profiles
  for (const p of CANONICAL_VERIFIED_PARTNERS) {
    await new Promise((resolve) => {
      db.run(
        `INSERT OR REPLACE INTO users (id, phone, email, password_hash, role, full_name, locality, onboarding_completed, is_active)
         VALUES (?, ?, ?, ?, 'WORKER', ?, ?, 1, 1)`,
        [p.userId, p.phone, p.email.toLowerCase(), `worker-verified-hash-${p.userId}`, p.name, p.locality],
        (uErr) => {
          if (uErr) console.warn('[Seed User Warn]', uErr.message);
          resolve();
        }
      );
    });

    await new Promise((resolve) => {
      db.run(
        `INSERT OR REPLACE INTO worker_profiles
         (id, user_id, trade_category, trade_title, experience_years, daily_rate, hourly_rate, visiting_charge, locality, city, bio, is_available, is_account_locked, kyc_status, rating_average, completed_jobs_count, packages_json, categories_json, latitude, longitude)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, 0, 'VERIFIED', ?, ?, ?, ?, ?, ?)`,
        [
          p.id,
          p.userId,
          p.tradeCategory,
          p.tradeTitle,
          p.experienceYears,
          p.dailyRate,
          p.hourlyRate,
          p.visitingCharge,
          p.locality,
          p.city,
          p.bio,
          p.ratingAverage,
          p.completedJobsCount,
          JSON.stringify(p.packages),
          JSON.stringify(p.categories),
          p.latitude,
          p.longitude
        ],
        (wErr) => {
          if (wErr) console.warn('[Seed WorkerProfile Warn]', wErr.message);
          resolve();
        }
      );
    });

    if (p.bank) {
      await new Promise((resolve) => {
        db.run(
          `INSERT OR REPLACE INTO worker_bank_kyc
           (id, worker_id, account_holder_name, account_number, ifsc_code, upi_id, bank_name, govt_id_type, govt_id_number, upi_phone, kyc_verified)
           VALUES (?, ?, ?, ?, ?, ?, ?, 'Aadhaar Card', '4591-2830-1928', ?, 1)`,
          [
            `kyc-${p.id}`,
            p.id,
            p.bank.holder,
            p.bank.accountNumber,
            p.bank.ifscCode,
            p.bank.upi,
            p.bank.bankName,
            p.bank.upiPhone
          ],
          () => resolve()
        );
      });
    }
  }

  console.log('⚡ [kaam Canonical Engine] 4 Verified Partner Profiles guaranteed and synced.');
}
